const existing = new Set();
for (const s of ['store','lib']) for (const g of ['유아','초등']) for (const b of books[s][g]) existing.add(b[0]);

const report = {};
for (const s of ['store','lib']) for (const g of ['유아','초등']) {
  const key = s + '.' + g;
  let added = 0, skipped = [];
  for (const b of NEW[s][g]) {
    if (books[s][g].length >= 100) break;
    const title = b[0];
    // 불완전/의심 후보(빈 필드 or 제목에 no/? 표시) 건너뛰기
    if (!title || !b[1] || !b[2] || /(\bno\b|\?$)/.test(title) === false && b[2] === '') { }
    if (!b[1] || !b[2] || title.includes(' no') || title.endsWith('? no')) { skipped.push(title); continue; }
    if (existing.has(title)) { skipped.push(title + '(중복)'); continue; }
    books[s][g].push(b); existing.add(title); added++;
  }
  report[key] = { total: books[s][g].length, added, skipped };
}

